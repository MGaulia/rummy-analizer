const assert = require('node:assert/strict');
const {PhotoSession, positionFromPhotos} = require('../phone/web/photo-state.js');
const raw = {text:'1', rect:{x:.1,y:.2,width:.1,height:.2}, candidates:[{tile:{color:'red',number:1},confidence:.8}]};
const table = new PhotoSession('table','table-photo',[raw]);
const rack = new PhotoSession('rack','rack-photo',[raw]);
assert.throws(() => table.confirm(true));
assert.throws(() => table.correct(table.observations[0].id, {color:'grey',number:1},1));
assert.throws(() => table.correct(table.observations[0].id, {color:'blue',number:1},0));
table.correct(table.observations[0].id,{color:'blue',number:1},1);
assert.equal(table.observations[0].raw.candidates[0].tile.color,'red');
raw.candidates[0].tile.color='black';
assert.equal(table.observations[0].raw.candidates[0].tile.color,'red');
assert.throws(() => table.confirm(false));
table.confirm(true);
assert.throws(() => positionFromPhotos(table,rack));
const missing = rack.add({x:0,y:0,width:.1,height:.1});
rack.correct(rack.observations[0].id,{joker:true});
rack.exclude(missing,true);rack.confirm(true);
const position=positionFromPhotos(table,rack);
assert.equal(position.table[0][0].tile.color,'blue');
assert.equal(position.rack[0].tile.joker,true);
assert.notEqual(position.table[0][0].id,position.rack[0].id);
assert.throws(() => positionFromPhotos(table,new PhotoSession('rack','table-photo')));
table.correct(table.observations[0].id,{color:'orange',number:1},1);
assert.throws(() => positionFromPhotos(table,rack));
assert.equal(rack.confirmed,true);
console.log('Photo state: uncertainty, correction isolation, missing/excluded tiles, distinct photos, and confirmation invalidation passed.');
const ordered = new PhotoSession('table','ordered',[raw,raw,raw]);
for(const [i,n] of [2,1,3].entries())ordered.correct(ordered.observations[i].id,{color:'blue',number:n},1,n);
ordered.confirm(true);
assert.deepEqual(positionFromPhotos(ordered,null,false).table[0].map(p=>p.tile.number),[1,2,3]);
ordered.correct(ordered.observations[2].id,{color:'blue',number:3},1,1);ordered.confirm(true);
assert.throws(()=>positionFromPhotos(ordered,null,false));
