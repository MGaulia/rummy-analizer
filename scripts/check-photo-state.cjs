const assert = require('node:assert/strict');
const {PhotoSession, positionFromPhotos, validTile} = require('../phone/web/photo-state.js');
const observation = (color,number,meld=1,order=1) => ({text:String(number),rect:{x:.1,y:.2,width:.1,height:.2},candidates:[{tile:{color,number},confidence:.8}],suggestedMeld:meld,suggestedOrder:order});
const raw = observation('red',1);
const table = new PhotoSession('table','table-photo',[raw]);
const rack = new PhotoSession('rack','rack-photo',[observation('black',9)]);
// Readable candidates are immediately usable without human confirmation.
assert.deepEqual(positionFromPhotos(table,rack).table[0][0].tile,{color:'red',number:1});
assert.equal(positionFromPhotos(table,rack).rack[0].tile.number,9);
assert.notEqual(table.pieces()[0].id,rack.pieces()[0].id);
assert.equal(table.observations[0].correction,null,'Automatic reading must not be labeled a user correction');
raw.candidates[0].tile.color='black';
assert.equal(table.observations[0].raw.candidates[0].tile.color,'red','Original input cannot mutate stored raw output');
const proposedPieces = table.pieces();
proposedPieces[0].tile.color='orange';
assert.equal(table.pieces()[0].tile.color,'red','Returned pieces cannot mutate stored proposals');
table.edit(table.observations[0].id,{color:'blue',number:1},1,1);
assert.equal(table.pieces()[0].tile.color,'blue');
assert.equal(table.observations[0].raw.candidates[0].tile.color,'red','Editing cannot change raw recognition');
const correctedPieces = table.pieces();
correctedPieces[0].tile.number=13;
const correctedReading = table.reading(table.observations[0].id);
correctedReading.tile.color='orange';
assert.deepEqual(table.pieces()[0].tile,{color:'blue',number:1},'Returned pieces/readings cannot mutate stored corrections');
table.edit(table.observations[0].id,{color:'grey',number:1},1);
assert.throws(()=>table.pieces(),/Could not read table tile 1/);
table.edit(table.observations[0].id,{color:'blue',number:1},0);
assert.throws(()=>table.pieces(),/meld number for table tile 1/);
// Every draft edit, including blanks and invalid values, overrides stale OCR.
table.edit(table.observations[0].id,{color:'blue',number:0},1,1);
assert.throws(()=>positionFromPhotos(table,rack),/table tile 1/);
table.edit(table.observations[0].id,{color:'blue',number:1},1,1);
assert.equal(positionFromPhotos(table,rack).table[0][0].tile.number,1);
table.edit(table.observations[0].id,{color:'blue',number:1},1,0);
assert.throws(()=>table.pieces(),/order/);
table.edit(table.observations[0].id,{color:'blue',number:1},1,1);
// Missing/ambiguous/invalid OCR must stop the move, never become an empty rack.
const unreadable = new PhotoSession('rack','uncertain',[{candidates:[]}]);
assert.throws(()=>positionFromPhotos(table,unreadable),/rack tile 1/);
const ambiguous = new PhotoSession('rack','ambiguous',[{candidates:[{tile:{color:'red',number:1}},{tile:{color:'red',number:11}}]}]);
assert.throws(()=>ambiguous.pieces(),/rack tile 1/);
const duplicateCandidates = new PhotoSession('rack','same-candidate',[{candidates:[{tile:{color:'red',number:1}},{tile:{color:'red',number:1}}]}]);
assert.equal(duplicateCandidates.pieces()[0].tile.number,1);
const invalid = new PhotoSession('rack','invalid',[{candidates:[{tile:{color:'red',number:14}}]}]);
assert.throws(()=>invalid.pieces(),/rack tile 1/);
assert.throws(()=>new PhotoSession('rack','empty').pieces(),/No rack tiles/);
assert.deepEqual(positionFromPhotos(new PhotoSession('table','empty-table'),rack).table,[]);
assert.throws(()=>new PhotoSession('table','failed',[],{error:'OCR failed'}).pieces(),/OCR failed/);
assert.throws(()=>new PhotoSession('rack','failed-rack',[observation('red',1)],{error:'Image could not be read'}).pieces(),/Image could not be read/);
assert.throws(()=>positionFromPhotos(null,rack),/table photo/);
assert.throws(()=>positionFromPhotos(table,null),/rack photo/);
assert.throws(()=>positionFromPhotos(table,new PhotoSession('rack','table-photo',[observation('red',1)])),/separate/);
// Manual additions and red-X removal preserve physical identity and raw output.
const added = rack.add({x:0,y:0,width:.1,height:.1});
assert.throws(()=>rack.pieces(),/rack tile 2/);
rack.edit(added,{joker:true});
assert.equal(rack.pieces()[1].tile.joker,true);
rack.exclude(added,true);
assert.equal(rack.pieces().length,1);
assert.equal(rack.observations[1].manual,true);
assert.deepEqual(rack.observations[1].raw.candidates,[]);
rack.exclude(added,false);
assert.equal(rack.pieces().length,2);
const copies = new PhotoSession('rack','copies',[observation('red',11),observation('red',11)]);
assert.equal(copies.pieces().length,2);
assert.notEqual(copies.pieces()[0].id,copies.pieces()[1].id);
copies.exclude(copies.observations[0].id,true);
assert.equal(copies.pieces()[0].id,copies.observations[1].id);
// Removal must preserve original numbering, fallback order and physical IDs.
const numbered = new PhotoSession('rack','numbered',[observation('red',1),{candidates:[]}]);
const secondId = numbered.observations[1].id;
numbered.exclude(numbered.observations[0].id);
assert.throws(()=>numbered.pieces(),/rack tile 2/);
numbered.edit(secondId,{joker:true});
assert.equal(numbered.pieces()[0].id,secondId);
assert.equal(numbered.pieces()[0].order,2);
numbered.exclude(secondId);
assert.throws(()=>numbered.pieces(),/No rack tiles/);
const ordered = new PhotoSession('table','ordered',[observation('blue',2,1,2),observation('blue',1,1,1),observation('blue',3,1,3)]);
assert.deepEqual(positionFromPhotos(ordered,null,false).table[0].map(p=>p.tile.number),[1,2,3]);
ordered.edit(ordered.observations[2].id,{color:'blue',number:3},1,1);
assert.throws(()=>positionFromPhotos(ordered,null,false),/same order/);
assert.throws(()=>new PhotoSession('table','no-meld',[{candidates:[{tile:{color:'red',number:1}}]}]).pieces(),/meld/);
for(const value of [null,{}, {color:'grey',number:1},{color:'red',number:0},{joker:true,color:'red'}])assert.ok(!validTile(value),JSON.stringify(value));
console.log('Photo state: automatic readable candidates, blocking uncertainty/invalid drafts, raw/correction isolation, distinct photos, exact duplicates, order, removal and read-failure checks passed.');
